#!/usr/bin/env python3
"""Regenerate analyses/panel-scores.jsonl from per-reviewer files.

Reads:  analyses/panel-scores-reviewer-*.jsonl  (one file per reviewer)
Writes: analyses/panel-scores.jsonl              (consolidated, deterministic order)

The consolidated file is the input to score_all.py's Fleiss κ computation.
This script is the producer; score_all.py is the consumer. Keeping them
separate lets per-reviewer files stay authoritative — the consolidated file
is a mechanical projection that can be regenerated byte-identically at any
time.

Validation (exits non-zero on any failure):
  - Required fields present and non-null on every row: rec_token, reviewer, score
  - No duplicate (rec_token, reviewer) pairs across all per-reviewer files
  - panel-routing.jsonl is readable

Orphans (rec_tokens not in panel-routing.jsonl) emit a warning to stderr but
are skipped, not errored. This matches score_all.py::attach_panel_kappa's
belt-and-suspenders policy: the scorer can still compute κ correctly even if
the consolidated file carries orphan rows. Filtering at write time keeps the
consolidated file tidy without making the producer fragile to corpus
regenesis.

Output ordering: sorted by (rec_token, reviewer) for byte-reproducibility.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REQUIRED_FIELDS = ("rec_token", "reviewer", "score")


def load_panel_routing_tokens(path: Path) -> set[str]:
    """Return the set of rec_tokens in panel-routing.jsonl."""
    tokens: set[str] = set()
    with path.open(encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            tokens.add(json.loads(line)["rec_token"])
    return tokens


def load_reviewer_file(path: Path) -> list[dict]:
    """Parse one panel-scores-reviewer-N.jsonl, validating required fields.

    Raises ValueError on malformed lines, missing fields, or null values in
    any required field. Empty lines are skipped silently to match how
    score_all.py reads the consolidated file.

    The null-rejection guards score_all.py::attach_panel_kappa, which buckets
    rows by `str(row["score"])` — a null score would silently bucket as
    "None" and corrupt the Fleiss κ computation downstream.
    """
    rows: list[dict] = []
    with path.open(encoding="utf-8") as f:
        for lineno, line in enumerate(f, 1):
            stripped = line.strip()
            if not stripped:
                continue
            try:
                row = json.loads(stripped)
            except json.JSONDecodeError as exc:
                raise ValueError(f"{path.name}:{lineno}: invalid JSON: {exc}") from exc
            missing = [f for f in REQUIRED_FIELDS if f not in row]
            if missing:
                raise ValueError(
                    f"{path.name}:{lineno}: missing required field(s): {', '.join(missing)}"
                )
            null_fields = [f for f in REQUIRED_FIELDS if row[f] is None]
            if null_fields:
                raise ValueError(
                    f"{path.name}:{lineno}: null value in required field(s): {', '.join(null_fields)}"
                )
            rows.append(row)
    return rows


def consolidate(
    reviewer_files: list[Path],
    valid_tokens: set[str],
) -> tuple[list[dict], list[tuple[str, dict]]]:
    """Read per-reviewer files, drop orphans, dedupe (rec_token, reviewer).

    Returns (kept_rows, orphan_rows). `orphan_rows` is a list of
    (filename, row) tuples for rec_tokens not in `valid_tokens` — the caller
    decides how to surface them.

    Raises ValueError on a duplicate (rec_token, reviewer) pair across files.
    """
    kept: list[dict] = []
    orphans: list[tuple[str, dict]] = []
    seen: set[tuple[str, str]] = set()
    for path in reviewer_files:
        rows = load_reviewer_file(path)
        for row in rows:
            pair = (row["rec_token"], row["reviewer"])
            if pair in seen:
                raise ValueError(
                    f"duplicate (rec_token, reviewer) pair across files: {pair}"
                )
            seen.add(pair)
            if row["rec_token"] not in valid_tokens:
                orphans.append((path.name, row))
                continue
            kept.append(row)
    kept.sort(key=lambda r: (r["rec_token"], r["reviewer"]))
    return kept, orphans


def write_consolidated(rows: list[dict], path: Path) -> None:
    """Write rows to path as compact JSONL (no spaces in separators)."""
    with path.open("w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, separators=(",", ":")) + "\n")


def main(argv: list[str] | None = None) -> int:
    here = Path(__file__).resolve().parent
    default_analyses = here / "analyses"
    default_reviewer_glob = "panel-scores-reviewer-*.jsonl"

    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "--analyses",
        type=Path,
        default=default_analyses,
        help="Directory holding per-reviewer files and panel-routing.jsonl.",
    )
    ap.add_argument(
        "--panel-routing",
        type=Path,
        default=None,
        help="panel-routing.jsonl path (defaults to <analyses>/panel-routing.jsonl).",
    )
    ap.add_argument(
        "--output",
        type=Path,
        default=None,
        help="Output panel-scores.jsonl path (defaults to <analyses>/panel-scores.jsonl).",
    )
    ap.add_argument(
        "--reviewer-glob",
        default=default_reviewer_glob,
        help=f"Glob (relative to --analyses) for per-reviewer files (default: {default_reviewer_glob}).",
    )
    args = ap.parse_args(argv)

    panel_routing = args.panel_routing or (args.analyses / "panel-routing.jsonl")
    output = args.output or (args.analyses / "panel-scores.jsonl")

    if not panel_routing.is_file():
        print(f"error: panel-routing.jsonl not found at {panel_routing}", file=sys.stderr)
        return 2

    reviewer_files = sorted(args.analyses.glob(args.reviewer_glob))
    if not reviewer_files:
        print(
            f"error: no per-reviewer files found matching {args.analyses}/{args.reviewer_glob}",
            file=sys.stderr,
        )
        return 2

    valid_tokens = load_panel_routing_tokens(panel_routing)
    print(
        f"panel-routing.jsonl: {len(valid_tokens)} unique rec_tokens",
        file=sys.stderr,
    )

    try:
        kept, orphans = consolidate(reviewer_files, valid_tokens)
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    for path in reviewer_files:
        with path.open(encoding="utf-8") as f:
            n = sum(1 for line in f if line.strip())
        print(f"  {path.name}: {n} rows", file=sys.stderr)

    if orphans:
        print(
            f"WARN: {len(orphans)} orphan rec_token(s) not in panel-routing.jsonl; skipped:",
            file=sys.stderr,
        )
        for filename, row in orphans[:5]:
            print(
                f"  {filename}: rec_token={row['rec_token']} reviewer={row['reviewer']}",
                file=sys.stderr,
            )
        if len(orphans) > 5:
            print(f"  ... and {len(orphans) - 5} more", file=sys.stderr)

    write_consolidated(kept, output)
    print(f"WROTE: {output} ({len(kept)} rows)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
